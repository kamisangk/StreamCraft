package db.migration;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.Statement;
import java.util.Locale;
import java.util.List;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/** Adds the durable ownership row used to fence concurrent Kafka transactions. */
public class V3__AddPipelineRunClaims extends BaseJavaMigration {

    @Override
    public void migrate(Context context) throws Exception {
        String databaseProduct = databaseProduct(context.getConnection());
        for (String statementSql : schemaStatements(databaseProduct)) {
            try (Statement statement = context.getConnection().createStatement()) {
                statement.execute(statementSql);
            }
        }
    }

    private String databaseProduct(Connection connection) throws Exception {
        return connection.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
    }

    private List<String> schemaStatements(String databaseProduct) {
        String claimIdDefinition;
        if (databaseProduct.contains("sqlite")) {
            claimIdDefinition = "integer primary key autoincrement";
        } else if (databaseProduct.contains("mysql")) {
            claimIdDefinition = "bigint not null auto_increment primary key";
        } else if (databaseProduct.contains("h2")) {
            claimIdDefinition = "bigint generated by default as identity primary key";
        } else {
            throw new IllegalStateException(
                    "Unsupported database for StreamCraft pipeline run claim migration: " + databaseProduct);
        }

        return List.of(
                """
                create table pipeline_run_claims (
                    id %s,
                    pipeline_id bigint not null,
                    job_id varchar(64) not null,
                    owner_token varchar(128) not null,
                    status varchar(32) not null check (status in ('SUBMITTING','RUNNING','RELEASED','FAILED')),
                    claimed_at timestamp not null,
                    updated_at timestamp not null,
                    last_error varchar(1000),
                    version bigint not null default 0,
                    constraint uk_pipeline_run_claim_pipeline unique (pipeline_id),
                    constraint fk_pipeline_run_claim_pipeline foreign key (pipeline_id) references pipelines(id) on delete cascade
                )
                """.formatted(claimIdDefinition),
                "create index idx_pipeline_run_claim_status on pipeline_run_claims(status)");
    }
}
